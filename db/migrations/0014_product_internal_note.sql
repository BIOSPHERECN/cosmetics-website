-- 产品加一列 internal_note:只给后台看,永不进前台渲染。
--
-- 起因很具体:公司资料里的爆品带着内部研发数据 ——
-- 「多孔包裹 SPF 提升 64%」「斑马鱼尾鳍修复 +19.07%」「依克多因 0.3%」。
-- 这些是内部实测,不是第三方验证过的功效宣称。
--
-- 我第一版把这些写进了 description 并加了「不对外宣称」的字样。
-- 前台恰好没渲染 description,所以没漏 —— 但那是**侥幸,不是设计**:
-- 哪天有人加了产品详情页,这些数字就会连同那句「不对外宣称」一起
-- 出现在公开页面上,而且看起来像是我们在正式宣称。
--
-- 靠约定不靠结构,迟早会破。所以单开一列:
--   description    公开文案,前台可以放心渲染
--   internal_note  只在后台出现,渲染层根本查不到这一列
-- ══════════════════════════════════════════════════════════════

ALTER TABLE products ADD COLUMN internal_note TEXT;
