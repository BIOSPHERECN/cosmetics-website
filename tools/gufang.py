DISCLAIM = ("古籍记载,非功效宣称。组成以通行本为准,不同版本与刻本略有出入;此处只列药味,"
            "不列剂量与煎服法。任何用于化妆品的复刻,均须按目标市场的原料目录与安全技术规范重新评估。")


def build():
    nodes = {}   # name -> (type, description)
    edges = []   # (name, type, description, [participants])

    def node(name, typ, desc):
        if name not in nodes:
            nodes[name] = (typ, desc)

    node("《化妆品安全技术规范》", "法规", "中国现行化妆品禁用与限用组分的依据文本。")
    for herb, why in BANNED.items():
        node(herb, "禁用或存疑组分", why)

    for name, book, era, use, herbs, record, modern in FORMULAS:
        node(name, "古方", f"{book}({era})· {use}。{record} {DISCLAIM}")
        node(book, "典籍", f"{era}代医籍。")
        for h in herbs:
            node(h, "药材", BANNED.get(h, f"古方组成药味,见于{name}等方。"))
        edges.append((f"{name} · 组成", "古方组成",
                      f"{book}所载{name}的组成药味(只列药味,不列剂量):"
                      + "、".join(herbs) + f"。{record}",
                      [name, book] + herbs))
        edges.append((f"{name} · 现代化妆品对应方向", "古方现代对应",
                      f"帛卉的解读(非古籍原文):{modern}",
                      [name] + [h for h in herbs if h in nodes]))
        bad = [h for h in herbs if h in BANNED]
        if bad:
            edges.append((f"{name} · 复刻前必须处理的组分", "化妆品禁用或限用组分",
                          "、".join(f"{h}({BANNED[h]})" for h in bad),
                          [name, "《化妆品安全技术规范》"] + bad))
    return nodes, edges


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    a = ap.parse_args()

    nodes, edges = build()
    herbs = sorted({h for *_x, hs, _r, _m in [(f[0], f[1], f[2], f[3], f[4], f[5], f[6]) for f in FORMULAS] for h in hs})
    print(f"古方 {len(FORMULAS)} 首 · 药材 {len(herbs)} 味 · 新节点 {len(nodes)} · 新超边 {len(edges)}")
    print(f"  含禁用/存疑组分的方: "
          f"{[f[0] for f in FORMULAS if any(h in BANNED for h in f[4])]}")
    if not a.apply:
        print("\n加 --apply 才写库")
        return

    have = {r["name"]: r["id"] for r in d1("SELECT id, name FROM kg_nodes")}
    maxn = d1("SELECT COALESCE(MAX(id),0) m FROM kg_nodes")[0]["m"]
    maxe = d1("SELECT COALESCE(MAX(id),0) m FROM kg_edges")[0]["m"]
    nid, eid = int(maxn), int(maxe)

    q = lambda v: "'" + str(v).replace("'", "''").replace(chr(10), " ") + "'"  # noqa: E731
    lines, newn = [], []
    for name, (typ, desc) in nodes.items():
        if name in have:
            continue
        nid += 1
        have[name] = nid
        newn.append(f"({nid},{q(name)},{q(typ)},{q(desc)},'classic')")
    for i in range(0, len(newn), 30):
        lines.append("INSERT INTO kg_nodes (id,name,type,description,origin) VALUES "
                     + ",".join(newn[i:i + 30]) + ";")
    erows, links = [], []
    for name, typ, desc, ps in edges:
        ids = [have[p] for p in ps if p in have]
        if len(ids) < 2:
            continue
        eid += 1
        erows.append(f"({eid},{q(name)},{q(typ)},{q(desc)},{len(ids)},'classic')")
        for x in ids:
            links.append(f"({eid},{x})")
    for i in range(0, len(erows), 30):
        lines.append("INSERT INTO kg_edges (id,name,type,description,arity,origin) VALUES "
                     + ",".join(erows[i:i + 30]) + ";")
    for i in range(0, len(links), 200):
        lines.append("INSERT OR IGNORE INTO kg_edge_nodes (edge_id,node_id) VALUES "
                     + ",".join(links[i:i + 200]) + ";")

    sql = os.path.join(HERE, "_gufang.sql")
    io.open(sql, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print(f"  新增节点 {len(newn)} · 新增超边 {len(erows)} · 参与者 {len(links)}")
    print(f"  SQL {os.path.getsize(sql):,} 字节 · 写入 {d1_exec(sql):,} 行")


if __name__ == "__main__":
    main()
