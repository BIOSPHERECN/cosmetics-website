"""古方入知识图谱 —— 24 首与皮肤、外用相关的古籍方,按超图结构入库。

由来(创始人 2026-09-10 08:29:「导入一些古方进去」「用知识图谱的方式呈现」)。

**三条纪律,和这份数据同等重要:**

1. **不写剂量。** 开剂量属于诊疗行为,我们是化妆品工厂不是医疗机构。
   这里只列组成(药味),不列一钱几分,也不列煎服法。
2. **认知档要标出来。** 每一首都标明出处典籍;组成以通行本为准,
   不同版本、不同刻本略有出入,这一句必须显示在页面上,不能让人以为是唯一定本。
   古籍记载 ≠ 功效宣称:页面上不得出现「祛斑」「美白」这类对产品的功效承诺,
   只能说「古籍记载用于…」。
3. **禁用组分必须标红。** 古方里常见轻粉(氯化亚汞)、铅粉、密陀僧(氧化铅)、
   朱砂(硫化汞)、雄黄(硫化砷)—— 这些在《化妆品安全技术规范》里是**禁用组分**,
   今天不得用于化妆品。把这一条明确写出来,比多收一首方子有价值得多:
   客户拿着古方来找我们复刻,第一件事就是要知道哪几味不能用。

**为什么用超边而不是两两关系:**
「七白膏 = 白芷 + 白蔹 + 白术 + 白茯苓 + 白及 + 白附子 + 细辛」是一条七方参与的事实。
拆成 7 条「七白膏—含有—X」的两两边之后,「这七味是一副方子」这个整体就没了。
超边把方名、典籍、全部药味放在同一条边上,这正是 Hyper-Extract 那套结构的用处。

用法:
    python tools/gufang.py            体检
    python tools/gufang.py --apply    写进 kg_nodes / kg_edges / kg_edge_nodes
"""
