def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    a = ap.parse_args()

    from collections import Counter
    print(f"检验环节 {len(STAGES)} 个 · 检验项 {len(ITEMS)} 条")
    print("  分布:", Counter(i[0] for i in ITEMS).most_common())
    for s in STAGES:
        n = sum(1 for i in ITEMS if i[0] == s[0])
        print(f"  {s[1]:<16} {n} 条 · {s[2][:40]}")
    if not a.apply:
        print("\n加 --apply 才写库")
        return

    q = lambda v: "'" + str(v).replace("'", "''").replace(chr(10), " ") + "'"  # noqa: E731
    lines = [
        "CREATE TABLE IF NOT EXISTS qc_stages (id TEXT PRIMARY KEY, name_zh TEXT, intro_zh TEXT,"
        " sort_order INTEGER);",
        "CREATE TABLE IF NOT EXISTS qc_items (code TEXT PRIMARY KEY, stage TEXT, name_zh TEXT,"
        " method_zh TEXT, spec_zh TEXT, sampling_zh TEXT, record_zh TEXT, sort_order INTEGER);",
        "CREATE INDEX IF NOT EXISTS idx_qc_items_stage ON qc_items(stage, sort_order);",
        "DELETE FROM qc_items;", "DELETE FROM qc_stages;",
    ]
    for i, (sid, nm, intro) in enumerate(STAGES):
        lines.append("INSERT INTO qc_stages (id,name_zh,intro_zh,sort_order) VALUES ("
                     + ",".join([q(sid), q(nm), q(intro), str((i + 1) * 10)]) + ");")
    for i, (stage, code, name, method, spec, sampling, record) in enumerate(ITEMS):
        lines.append("INSERT INTO qc_items (code,stage,name_zh,method_zh,spec_zh,sampling_zh,record_zh,sort_order)"
                     " VALUES (" + ",".join([q(code), q(stage), q(name), q(method), q(spec),
                                             q(sampling), q(record), str((i + 1) * 10)]) + ");")
    sql = os.path.join(HERE, "_qc-system.sql")
    io.open(sql, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print(f"  SQL {os.path.getsize(sql):,} 字节 · 写入 {d1_exec(sql):,} 行")
    n = d1("SELECT COUNT(*) n FROM qc_items")
    print(f"完成:qc_items 共 {n[0]['n'] if n else '?'} 条")


if __name__ == "__main__":
    main()
