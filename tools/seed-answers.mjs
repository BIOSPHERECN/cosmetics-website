const sql = [];
let nextId = (d1('SELECT MAX(id) m FROM blocks')[0].m ?? 0) + 1;
let n = 0;

for (const [site, slug, data] of ANSWERS) {
  const page = d1(`SELECT id FROM pages WHERE site_id=${lit(site)} AND slug=${lit(slug)} LIMIT 1`)[0];
  if (!page) { console.warn(`  跳过:${site} 没有 /${slug}`); continue; }

  const exist = d1(`SELECT id FROM blocks WHERE page_id=${page.id} AND type='answer' LIMIT 1`)[0];
  const id = exist?.id ?? nextId++;
  if (!exist) {
    /* sort_order 给 5:排在店招/首图之后、其余内容之前。
       「开头直答」的价值就在**开头** —— 排到第三屏等于没做。 */
    sql.push(`INSERT INTO blocks (id,page_id,type,sort_order,config_json,is_visible) VALUES (${id},${page.id},'answer',5,'{}',1);`);
  }
  sql.push(`INSERT INTO block_i18n (block_id,lang,data_json,mt,mt_at) VALUES (${id},'zh-cn',${J(data)},0,datetime('now'))
            ON CONFLICT(block_id,lang) DO UPDATE SET data_json=excluded.data_json,mt=0,mt_at=excluded.mt_at;`);
  sql.push(`DELETE FROM block_i18n WHERE block_id=${id} AND lang<>'zh-cn';`);
  n++;
  console.log(`  ${site} /${slug || '首页'}  ${data.faqs.length} 条常见问题`);
}

const OUT = 'F:/0cosmetic/cosmetic-sites/node_modules/.cache/answers.sql';
writeFileSync(OUT, sql.join('\n'), 'utf8');
d1(OUT, { file: true });
console.log(`\n开头直答版块:${n} 个`);
