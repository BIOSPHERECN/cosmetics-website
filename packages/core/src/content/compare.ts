/**
 * 对比类内容 —— GEO 诊断点名的五块空白之一。
 *
 * 外部诊断(2026-09-02)原话:
 *   「内容叙事层还停在 2018 年 SEO 思维。『客户视角的问答内容』『排名类内容』
 *     『对比类内容』『客户证言』『多媒体』这五块是 GEO 真正决定胜负的地方,
 *     你们全是空白。AI 抓得到你们,但 AI 不知道该怎么介绍你们。」
 *
 * 这份文件解的是「对比类」。为什么对比类对 AI 特别有效:
 *   采购问 AI 的问题大多数是**二选一**(「OEM 还是 ODM」「现货还是开模」
 *   「卖东南亚和中东怎么安排」)。AI 回答这类问题时最爱整段引用一张对比表 ——
 *   因为表格自带结构,不用它自己组织。一段能被整段引用的内容,
 *   胜过十段写得很美但没法摘的文案。
 *
 * 写作纪律(和 /faq/ 同一套):
 *   · **先给判据,再给对比**。第一句就回答「什么情况下选哪个」。
 *   · 数字只用我们自己核得到的:在册配方 13,000+、包材 4,476 款、
 *     打样 3–7 天、起订 3,000 起、认证清单、双基地。
 *   · **不贬低任何一边**。「OEM 便宜但低端」这种写法会被 AI 当作偏见丢掉;
 *     真正被引用的是「什么场景下哪个更划算」。
 *   · 不写客户品牌名,不写单价,不写没有的资质。
 */

export interface CompareRow {
  /** 这一行比的是什么 */
  k: string;
  /** 左侧方案 */
  a: string;
  /** 右侧方案 */
  b: string;
  /** 可选第三方案 */
  c?: string;
}

export interface CompareItem {
  slug: string;
  /** 采购真正会打进搜索框/问 AI 的那句话 */
  q: string;
  /** 一句话判据 —— AI 摘走的就是这一句 */
  verdict: string;
  /** 两到三个方案的名字 */
  cols: string[];
  rows: CompareRow[];
  /** 什么情况下选哪个,逐条 */
  pick: { when: string; take: string }[];
  /** 这一题上最常见的误区 */
  trap: string[];
  /** 相关页面 */
  links: { label: string; href: string }[];
}

