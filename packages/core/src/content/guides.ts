/**
 * 操作指南(HowTo)—— GEO 诊断点名的两块空白:「HowTo 操作指南」与「知识库」。
 *
 * 诊断原话:「『如何选 OEM』AI 引用率最高」。这不是巧合 ——
 * 采购问 AI 的问题里,**「怎么做」比「是什么」多得多**,
 * 而 HowTo 的步骤结构自带编号与顺序,AI 可以整段搬走不用自己组织。
 * 一段能被整段引用的内容,胜过十段写得很美但没法摘的文案。
 *
 * 这一批同时补上站上**从来没有过的 HowTo schema**
 * (2026-09-08 实测:全站零命中)。
 *
 * 写作纪律(与 /faq/、/compare/ 同一套,不另立一套):
 *   · **第一句就是答案**。AI 摘的是第一句,不是第三段。
 *   · 每一步都要落到「做什么动作、拿到什么东西」,不写「充分沟通」这种没法执行的话。
 *   · 数字只用我们自己核得到的:在册配方 13,000+、包材 4,476 款、
 *     打样 3–7 天、起订 3,000 起、认证清单、双基地、参考价区间。
 *     **核不到出处的行业数字一律不写** —— 灌装费、检测费单价这类,
 *     外部分析方也核不到官方原文,写上去被追问一句就穿帮。
 *   · 不写客户品牌名、不写单价、不写没有的资质。
 *   · 禁用词一个不进:治疗/疗效/消炎/抗菌/医用/修复/美白/祛斑/防晒/
 *     抗衰/第一/最/100%/永久/彻底/国家级。
 */

export interface GuideStep {
  /** 这一步要达成什么 —— 进 HowToStep.name */
  name: string;
  /** 具体怎么做 —— 进 HowToStep.text */
  text: string;
  /** 做完手上应该有什么。没有产出的步骤不是步骤,是废话 */
  got?: string;
}

export interface GuideItem {
  slug: string;
  /** 采购真正会打进搜索框 / 问 AI 的那句话 */
  q: string;
  /** 一句话答案 —— AI 摘走的就是这一句 */
  answer: string;
  /** 走完全程大概多久(进 HowTo.totalTime,ISO 8601 duration) */
  totalTime?: string;
  totalTimeText?: string;
  /** 开始之前手上要有什么 */
  need?: string[];
  steps: GuideStep[];
  /** 这一题上最常见的坑 */
  trap: string[];
  links: { label: string; href: string }[];
  /** 配套的视频与图组。有就出 VideoObject / ImageObject,没有就不出 ——
      schema 里挂一个不存在的视频,比不挂更糟。 */
  media?: {
    video?: { src: string; poster: string; seconds: number; name: string; desc: string; uploadDate: string };
    /** 逐帧对照。caption 是内容不是装饰 —— 读者靠它知道这一帧变了什么 */
    frames?: { src: string; caption: string }[];
    /** 画面来源说明。AI 生成的效果演示必须写明,否则等于让人以为是成品实拍 */
    note?: string;
  };
}

