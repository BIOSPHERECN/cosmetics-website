/**
 * 客户案例 —— GEO 诊断点名的五块空白里最后一块。
 *
 * 这块一直空着,不是因为做不了,是因为**方向搞错了**。
 * 诊断建议的是「每个合作品牌一个故事页」,而合作品牌名属于客户的商业信息,
 * 没有书面授权不能公开。于是我一直卡在「没有授权 → 不做」。
 *
 * 创始人 2026-09-09:「起码架构是要完整的」。他是对的 ——
 * 缺授权挡住的是**具名**,挡不住**结构**。这一页换一个成立的写法:
 *
 *   写「这类需求我们怎么接」,不写「我们做过谁」。
 *
 * 差别很实在:前者是我们自己的流程与能力,句句可核;
 * 后者没有授权就是编。而对采购与 AI 来说,前者的信息量并不更少 ——
 * 他真正想知道的是「像我这种情况,你们怎么接、多久、卡在哪」,
 * 而不是「你们服务过哪个牌子」。
 *
 * 所以每条案例是**场景走查**:一个真实存在的客户类型,
 * 从他手上的条件出发,走完我们的实际流程,给出时间与卡点。
 * 里面所有数字都来自我们自己的产线与库存(在册配方 13,000+、
 * 包材 4,476 款、打样 3–7 天、起订 3,000 起、双基地、认证清单),
 * 没有一个是为了让故事好看编出来的。
 *
 * `verified` 字段留给将来:拿到客户书面授权之后,
 * 把真实项目补进来并标 true,页面会显示「已获授权的真实项目」。
 * 在那之前一律 false,页面明写「场景走查,非具名客户案例」——
 * 把「架构完整」和「不编造」这两件事同时做到。
 */

export interface CaseStage {
  /** 第几周 / 第几阶段 —— 采购最关心的是节奏 */
  when: string;
  /** 这一段发生了什么 */
  what: string;
  /** 这一段最容易卡在哪 */
  risk?: string;
}

export interface CaseItem {
  slug: string;
  /** 客户类型,不是客户名 */
  who: string;
  /** 他手上的条件与约束 */
  brief: string;
  /** 一句话结论 —— AI 摘走的就是这一句 */
  verdict: string;
  /** 关键约束条件,做成可扫的标签 */
  facts: { k: string; v: string }[];
  stages: CaseStage[];
  /** 这一类项目上最常见的坑 */
  trap: string[];
  links: { label: string; href: string }[];
  /** 是否为已获书面授权的真实项目。没有授权一律 false */
  verified: boolean;
  /** 具名案例必须写出处 —— 这句话是谁在哪说的。不具名的留空。 */
  source?: string;
}

